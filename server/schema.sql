CREATE TABLE IF NOT EXISTS restaurant_tables (
  id SMALLINT PRIMARY KEY,
  floor_number SMALLINT NOT NULL,
  min_capacity SMALLINT NOT NULL,
  max_capacity SMALLINT NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT chk_table_capacity CHECK (
    min_capacity >= 1 AND max_capacity >= min_capacity
  )
);

CREATE INDEX IF NOT EXISTS idx_tables_floor_active
  ON restaurant_tables (floor_number, is_active);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(254) NOT NULL,
  password_hash CHAR(128) NOT NULL,
  password_salt CHAR(32) NOT NULL,
  role VARCHAR(24) NOT NULL DEFAULT 'customer',
  staff_id VARCHAR(16),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_users_email UNIQUE (email),
  CONSTRAINT uq_users_staff_id UNIQUE (staff_id),
  CONSTRAINT chk_users_role CHECK (role IN ('customer', 'staff', 'manager')),
  CONSTRAINT chk_users_staff_id CHECK (
    (role = 'staff' AND staff_id IS NOT NULL) OR
    (role <> 'staff' AND staff_id IS NULL)
  )
);

CREATE TABLE IF NOT EXISTS auth_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_auth_sessions_expiry
  ON auth_sessions (expires_at);
CREATE INDEX IF NOT EXISTS idx_auth_sessions_user
  ON auth_sessions (user_id);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_expiry
  ON password_reset_tokens (expires_at);
CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_user
  ON password_reset_tokens (user_id);

CREATE TABLE IF NOT EXISTS menu_overrides (
  menu_item_id VARCHAR(32) PRIMARY KEY,
  item_name VARCHAR(120) NOT NULL,
  price_cents INTEGER NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_menu_override_price CHECK (price_cents > 0)
);

CREATE TABLE IF NOT EXISTS reservations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_id SMALLINT NOT NULL REFERENCES restaurant_tables (id),
  booking_date DATE NOT NULL,
  booking_time TIME NOT NULL,
  party_size SMALLINT NOT NULL,
  customer_name VARCHAR(120) NOT NULL,
  customer_email VARCHAR(254) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_reservation_party_size CHECK (party_size >= 1),
  CONSTRAINT uq_reservation_table_slot
    UNIQUE (table_id, booking_date, booking_time)
);

CREATE INDEX IF NOT EXISTS idx_reservations_date_time
  ON reservations (booking_date, booking_time);

CREATE TABLE IF NOT EXISTS orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_email VARCHAR(254) NOT NULL,
  total_amount NUMERIC(10, 2) NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'ZAR',
  status VARCHAR(24) NOT NULL DEFAULT 'pending',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  order_email_sent_at TIMESTAMPTZ,
  paid_email_sent_at TIMESTAMPTZ,
  CONSTRAINT chk_orders_total CHECK (total_amount > 0),
  CONSTRAINT chk_orders_status CHECK (status IN ('pending', 'paid', 'cancelled'))
);

CREATE TABLE IF NOT EXISTS order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  menu_item_id VARCHAR(32) NOT NULL,
  item_name VARCHAR(120) NOT NULL,
  quantity SMALLINT NOT NULL,
  unit_price NUMERIC(10, 2) NOT NULL,
  line_total NUMERIC(10, 2) NOT NULL,
  CONSTRAINT chk_order_items_quantity CHECK (quantity >= 1),
  CONSTRAINT chk_order_items_price CHECK (unit_price > 0 AND line_total > 0)
);

CREATE INDEX IF NOT EXISTS idx_order_items_order ON order_items (order_id);

CREATE TABLE IF NOT EXISTS payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  amount NUMERIC(10, 2) NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'ZAR',
  method VARCHAR(24) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'pending',
  provider_reference VARCHAR(128),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_payments_amount CHECK (amount > 0),
  CONSTRAINT chk_payments_method CHECK (method IN ('card', 'yoco')),
  CONSTRAINT chk_payments_status CHECK (
    status IN ('pending', 'authorized', 'paid', 'failed', 'cancelled')
  )
);

CREATE INDEX IF NOT EXISTS idx_payments_order ON payments (order_id);

